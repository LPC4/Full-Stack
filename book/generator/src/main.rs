//! Static site generator for the Full-Stack book.

#![allow(
    clippy::print_stdout,
    reason = "CLI binary reports what it built on stdout"
)]
#![allow(clippy::print_stderr, reason = "CLI binary reports failures on stderr")]

mod code;
mod config;
mod page;
mod render;
mod sandbox;
mod serve;
mod split;

use config::Config;
use split::{Level, Page};
use std::path::{Path, PathBuf};
use std::process::ExitCode;

const USAGE: &str = "usage: fsbook <build|serve> [--root DIR] [--out DIR] [--port N]\n\
                     \x20      [--no-sandbox] [--rebuild-sandbox]";

struct Args {
    root: PathBuf,
    out: PathBuf,
    serve: bool,
    port: u16,
    sandbox: bool,
    rebuild_sandbox: bool,
}

fn parse_args() -> Result<Args, String> {
    let mut root = PathBuf::from(".");
    let mut out = None;
    let mut serve = false;
    let mut port = 8000;
    let mut sandbox = true;
    let mut rebuild_sandbox = false;
    let mut argv = std::env::args().skip(1);

    while let Some(arg) = argv.next() {
        match arg.as_str() {
            "build" => {}
            "serve" => serve = true,
            "--root" => root = argv.next().ok_or("--root needs a path")?.into(),
            "--out" => out = Some(PathBuf::from(argv.next().ok_or("--out needs a path")?)),
            "--port" => {
                let value = argv.next().ok_or("--port needs a number")?;
                port = value
                    .parse()
                    .map_err(|e| format!("bad port `{value}`: {e}"))?;
            }
            "--no-sandbox" => sandbox = false,
            "--rebuild-sandbox" => rebuild_sandbox = true,
            "-h" | "--help" => return Err(USAGE.into()),
            other => return Err(format!("unknown argument `{other}`")),
        }
    }
    let out = out.unwrap_or_else(|| root.join("out"));
    Ok(Args {
        root,
        out,
        serve,
        port,
        sandbox,
        rebuild_sandbox,
    })
}

fn copy_dir(from: &Path, to: &Path) -> std::io::Result<usize> {
    if !from.is_dir() {
        return Ok(0);
    }
    std::fs::create_dir_all(to)?;
    let mut copied = 0;
    for entry in std::fs::read_dir(from)? {
        let entry = entry?;
        let source = entry.path();
        let target = to.join(entry.file_name());
        if source.is_dir() {
            copied += copy_dir(&source, &target)?;
        } else {
            std::fs::copy(&source, &target)?;
            copied += 1;
        }
    }
    Ok(copied)
}

// Records resolved slugs so URL churn shows up in review rather than silently.
fn write_summary(root: &Path, pages: &[Page]) -> std::io::Result<()> {
    let mut out = String::from("# Generated by `fsbook build`. Do not edit.\n\n");
    for page in pages {
        let kind = match page.level {
            Level::Index => "index",
            Level::Chapter => "chapter",
            Level::Section => "section",
        };
        out.push_str(&format!(
            "[[page]]\nkind = \"{kind}\"\nslug = \"{}\"\ntitle = \"{}\"\n\n",
            page.slug,
            page.title.replace('"', "\\\"")
        ));
    }
    std::fs::write(root.join("src/SUMMARY.toml"), out)
}

fn run() -> Result<(), String> {
    let args = parse_args()?;
    let root = &args.root;
    let config = Config::load(&root.join("book.toml"))?;
    let figures = root.join("figures");

    let no_toolchain = if args.sandbox {
        matches!(
            sandbox::ensure(root, args.rebuild_sandbox)?,
            sandbox::Outcome::NoToolchain
        )
    } else {
        false
    };

    let mut pages = Vec::new();
    for part in &config.parts {
        let source = root.join(&part.source);
        let markdown = std::fs::read_to_string(&source)
            .map_err(|e| format!("cannot read {}: {e}", source.display()))?;
        pages.extend(split::split(&part.title, &markdown));
    }
    if pages.is_empty() {
        return Err("no pages were produced".into());
    }

    if args.out.exists() {
        std::fs::remove_dir_all(&args.out)
            .map_err(|e| format!("cannot clear {}: {e}", args.out.display()))?;
    }

    let mut missing_figures = Vec::new();
    for (index, current) in pages.iter().enumerate() {
        let context = render::Context {
            path_to_root: &current.path_to_root(),
            repo_url: config.repo_url.as_deref(),
            figures: &figures,
        };
        let rendered = render::render(&current.body, &context);
        let html = page::build(&config, &pages, index, &rendered);

        let target = args.out.join(format!("{}.html", current.slug));
        if let Some(parent) = target.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|e| format!("cannot create {}: {e}", parent.display()))?;
        }
        std::fs::write(&target, html)
            .map_err(|e| format!("cannot write {}: {e}", target.display()))?;

        collect_missing_figures(&current.body, &figures, &mut missing_figures);
    }

    let mut theme = copy_dir(&root.join("theme"), &args.out.join("theme"))
        .map_err(|e| format!("cannot copy theme: {e}"))?;
    let shared_theme = root.join("../theme/github-dark.css");
    std::fs::copy(&shared_theme, args.out.join("theme/github-dark.css"))
        .map_err(|e| format!("cannot copy {}: {e}", shared_theme.display()))?;
    theme += 1;
    // Absent when wasm-pack is unavailable or the sandbox was skipped, which is fine.
    let sandbox_files = copy_dir(&root.join("wasm/pkg"), &args.out.join("sandbox"))
        .map_err(|e| format!("cannot copy sandbox: {e}"))?;
    let figure_files = copy_dir(&figures, &args.out.join("figures"))
        .map_err(|e| format!("cannot copy figures: {e}"))?;
    write_summary(root, &pages).map_err(|e| format!("cannot write SUMMARY.toml: {e}"))?;

    let sections = pages.iter().filter(|p| p.level == Level::Section).count();
    println!(
        "{} pages ({sections} sections), {theme} theme files, {figure_files} figures, \
         {sandbox_files} sandbox files -> {}",
        pages.len(),
        args.out.display()
    );
    if sandbox_files == 0 {
        let why = if no_toolchain {
            "wasm-pack is not on PATH; `cargo install wasm-pack` to enable Run buttons"
        } else {
            "no sandbox bundle; Run buttons will be inert"
        };
        println!("note: {why}");
    }

    if !missing_figures.is_empty() {
        missing_figures.sort();
        missing_figures.dedup();
        return Err(format!(
            "referenced figures are missing from {}: {}",
            figures.display(),
            missing_figures.join(", ")
        ));
    }

    if args.serve {
        serve::serve(&args.out, args.port)?;
    }
    Ok(())
}

// A broken figure reference should fail the build, not ship a broken image.
fn collect_missing_figures(markdown: &str, figures: &Path, missing: &mut Vec<String>) {
    let mut rest = markdown;
    while let Some(at) = rest.find("](figures/") {
        rest = &rest[at + 2..];
        let Some(end) = rest.find(')') else { break };
        let path = &rest[..end];
        let name = path.trim_start_matches("figures/");
        if !figures.join(name).is_file() {
            missing.push(name.to_owned());
        }
        rest = &rest[end..];
    }
}

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("fsbook: {message}");
            ExitCode::FAILURE
        }
    }
}
